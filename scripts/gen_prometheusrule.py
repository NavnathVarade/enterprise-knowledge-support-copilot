"""Render monitoring/prometheus/alerts.yaml into a PrometheusRule manifest.

python -m scripts.gen_prometheusrule          # write
python -m scripts.gen_prometheusrule --check  # exit 1 if the file is stale (CI)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "monitoring" / "prometheus" / "alerts.yaml"
DST = ROOT / "infrastructure" / "kubernetes" / "base" / "prometheusrule.yaml"
HEADER = "# GENERATED by scripts/gen_prometheusrule.py from monitoring/prometheus/alerts.yaml.\n# Do not edit by hand.\n"


def render() -> str:
    groups = yaml.safe_load(SRC.read_text())["groups"]
    doc = {
        "apiVersion": "monitoring.coreos.com/v1",
        "kind": "PrometheusRule",
        "metadata": {"name": "ekc-alerts", "labels": {"release": "prometheus"}},
        "spec": {"groups": groups},
    }
    return HEADER + str(yaml.safe_dump(doc, sort_keys=False, width=100))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    out = render()
    if args.check:
        if not DST.exists() or DST.read_text() != out:
            print("prometheusrule.yaml is stale; run: python -m scripts.gen_prometheusrule")
            return 1
        return 0
    DST.write_text(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
