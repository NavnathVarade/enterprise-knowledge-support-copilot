"""Generates the reference docs that must never drift from the code (Phase 47).

  docs/reference/CONFIGURATION.md  - every environment variable, from `packages.config.settings`
  docs/reference/API.md            - every HTTP operation, from the FastAPI OpenAPI schema

Usage: python scripts/gen_reference_docs.py [--check]
--check exits 1 (and prints which file) if a committed file differs from what the code produces.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from typing import Any

from pydantic import SecretStr
from pydantic_core import PydanticUndefined
from pydantic_settings import BaseSettings

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reference"

HEADER = "<!-- GENERATED by scripts/gen_reference_docs.py - do not edit; run the script. -->\n\n"


def _cell(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


def _default(field: Any) -> str:
    if field.is_required():
        return "**required**"
    default = field.get_default(call_default_factory=False)
    if default is PydanticUndefined or default is None:
        return "unset"
    if isinstance(default, SecretStr):
        return "(secret)"
    if hasattr(default, "value"):  # enum
        return f"`{default.value}`"
    return f"`{default}`" if str(default) != "" else '`""`'


def _env_name(prefix: str, name: str, field: Any) -> str:
    alias = field.validation_alias
    if isinstance(alias, str):
        return alias
    return f"{prefix}{name}".upper()


def configuration_markdown() -> str:
    from packages.config.settings import Settings

    lines = [
        HEADER,
        "# Configuration reference\n",
        "All configuration is read from environment variables. `ENVIRONMENT` (`development`, `test`, "
        "`staging`, `production`; default **production**) selects how strict validation is: outside "
        "development/test the application refuses to start on localhost-style hosts, plaintext Kafka, "
        "unencrypted Postgres/Redis (unless `HARDENING_REQUIRE_DEPENDENCY_TLS=false`) and the committed "
        "test JWT key. Secrets (marked below) must come from a secret manager, never from the repository.\n",
        "| Variable | Default | Description |",
        "|---|---|---|",
        f"| `ENVIRONMENT` | `{Settings.model_fields['environment'].default.value}` | Deployment environment |",
    ]
    for group in Settings.model_fields.values():
        sub = group.annotation
        if not (isinstance(sub, type) and issubclass(sub, BaseSettings)):
            continue
        prefix = str(sub.model_config.get("env_prefix", ""))
        for name, field in sub.model_fields.items():
            secret = "SecretStr" in str(field.annotation)
            desc = (field.description or "") + (" **Secret.**" if secret else "")
            lines.append(
                f"| `{_env_name(prefix, name, field)}` | {_cell(_default(field))} | {_cell(desc)} |"
            )
    return "\n".join(lines) + "\n"


def api_markdown() -> str:
    os.environ.setdefault("ENVIRONMENT", "test")
    from apps.api.app.main import create_app

    schema = create_app().openapi()
    lines = [
        HEADER,
        "# HTTP API reference\n",
        f"{schema['info'].get('title', '')} - version {schema['info'].get('version', '')}. "
        "Every operation except login and the health probes requires `Authorization: Bearer <JWT>`; "
        'errors use `{"error": {"code", "message", "request_id"}}`. `/metrics` is served only with '
        "a bearer token configured and is not part of this schema. Interactive docs are disabled in "
        "staging/production.\n",
        "| Method | Path | Summary |",
        "|---|---|---|",
    ]
    for path, ops in sorted(schema["paths"].items()):
        for method, op in sorted(ops.items()):
            lines.append(f"| {method.upper()} | `{path}` | {_cell(op.get('summary', ''))} |")
    lines.append("\n## Request and response bodies\n")
    for name, comp in sorted(schema.get("components", {}).get("schemas", {}).items()):
        props = comp.get("properties", {})
        if not props:
            continue
        req = set(comp.get("required", []))
        lines.append(f"### {name}\n")
        lines.append("| Field | Type | Required |")
        lines.append("|---|---|---|")
        for pname, p in props.items():
            ptype = p.get("type") or p.get("$ref", "").rsplit("/", 1)[-1] or "any"
            if "anyOf" in p:
                ptype = " or ".join(
                    sorted(
                        {a.get("type") or a.get("$ref", "").rsplit("/", 1)[-1] for a in p["anyOf"]}
                    )
                )
            lines.append(f"| `{pname}` | {_cell(ptype)} | {'yes' if pname in req else 'no'} |")
        lines.append("")
    return "\n".join(lines) + "\n"


FILES = {"CONFIGURATION.md": configuration_markdown, "API.md": api_markdown}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    stale = []
    for name, build in FILES.items():
        text, path = build(), OUT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        print(
            "stale generated docs (run: python scripts/gen_reference_docs.py): " + ", ".join(stale)
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
