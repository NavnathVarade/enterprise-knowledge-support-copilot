"""
Deterministic local embedding provider.

NOT semantically meaningful -- this does not capture any real notion of textual
similarity the way a trained embedding model does. What it DOES give, honestly and
usefully: a real, reproducible mapping from text to a unit-length vector of the
configured dimensionality, generated by seeding a PRNG from the text's SHA-256 hash.
The same text always produces the exact same vector; different texts produce different
vectors; the vector is genuinely unit-normalized, so cosine similarity/distance
operations against it behave the way they would against a real embedding, just without
real semantic content behind them.

This exists because no real embedding provider is reachable from this development
environment's network (Anthropic has no native embeddings endpoint; Voyage AI's API
host isn't in the allowlist) -- see docs/rag/PHASE_11_EMBEDDING_DESIGN.md. It lets the
storage, retrieval-query, and pipeline-wiring code be genuinely tested against a real
pgvector column, with the semantic-quality question left honestly unanswered until a
real provider is connected.
"""

from __future__ import annotations

import random

from packages.domain.hashing import sha256_hex_of_text


class DeterministicLocalEmbeddingProvider:
    def __init__(
        self, *, dimensions: int = 1024, model_name: str = "deterministic-local-v1"
    ) -> None:
        self._dimensions = dimensions
        self._model_name = model_name

    @property
    def model_name(self) -> str:
        return self._model_name

    @property
    def dimensions(self) -> int:
        return self._dimensions

    def _embed_one(self, text: str) -> list[float]:
        seed_hex = sha256_hex_of_text(text)
        seed = int(seed_hex, 16) % (2**32)
        # Deterministic test-double vectors, not a security primitive.
        rng = random.Random(seed)  # nosec B311
        raw = [rng.uniform(-1.0, 1.0) for _ in range(self._dimensions)]
        norm = sum(v * v for v in raw) ** 0.5
        if norm == 0:
            raw[0] = 1.0
            norm = 1.0
        return [v / norm for v in raw]

    async def embed_batch(self, texts: list[str]) -> list[list[float]]:
        return [self._embed_one(t) for t in texts]

    async def embed_query(self, text: str) -> list[float]:
        return self._embed_one(text)
